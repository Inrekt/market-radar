// Составной скор монеты: среднее по ИЗМЕРЕННЫМ метрикам.
//
// Почему знаменатель — только измеренные, а не все метрики. Архив пока мелкий,
// и часть метрик обязана молчать (score === null). Если делить сумму на общее
// число метрик, монета с двумя молчащими получает вдвое меньший скор при ровно
// тех же показаниях — сканер начинает систематически слепнуть именно там, где
// данных меньше, и снаружи это выглядит как «там ничего не происходит», а не
// как «мы там не смотрим». Поэтому среднее берётся по измеренным, а сколько их
// было — видно в available, и решение «доверять ли» остаётся за вызывающим.

import type { Metric } from './metrics.js'

export interface Scored {
  /** сумма вкладов доступных метрик, 0..1 после нормировки */
  readonly score: number
  /** сколько метрик реально измерено */
  readonly available: number
  /** сколько метрик всего */
  readonly total: number
  /** метрики с наибольшим вкладом, до трёх */
  readonly top: readonly Metric[]
}

/**
 * Сколько причин показываем человеку. Три ещё читаются одним взглядом,
 * пять превращают пинг в отчёт, который пролистывают не читая.
 */
const MAX_TOP_METRICS = 3

/**
 * Порог достоверности: ниже трёх измеренных метрик скор — это мнение одной-двух
 * цифр, и любая из них может быть просто шумом одного снимка. Функция всё равно
 * вернёт score (прятать число незачем), но вызывающий обязан посмотреть на
 * available и решить сам — молчать или слать.
 */
export const MIN_RELIABLE_METRICS = 3

/**
 * Порог пинга. Откалиброван по РАСПРЕДЕЛЕНИЮ, а не выбран на глаз.
 *
 * Замер 28.08.2026 по 35 монетам с оборотом от $5M на одном срезе рынка:
 * медиана скора 0.026, 75-й перцентиль 0.079, 90-й 0.101, 95-й 0.220,
 * максимум 0.333. При 0.30 проходит примерно одна монета из тридцати пяти;
 * вместе с четырёхчасовым кулдауном по монете часовой бюджет остаётся запасом,
 * а не главным ограничителем.
 *
 * Честные границы этого числа: срез один и рынок в нём был спокойный (никто не
 * дотянул даже до 0.35). В бурный час порог пропустит больше, и тогда отбор
 * ляжет на бюджет — это и есть его назначение. Пересмотреть, когда накопится
 * месяц архива и табель триггеров покажет, что из отправленного чего стоило.
 */
export const ALERT_THRESHOLD = 0.30

/** Метрика с настоящим числом внутри: null и NaN сюда не проходят. */
type MeasuredMetric = Metric & { readonly score: number }

/**
 * NaN и Infinity — это сломанная метрика, а не измерение. Считать их нулём
 * значит занизить скор выдуманным числом, считать единицей — поднять. Обе
 * подмены выглядят как показание, поэтому такая метрика приравнивается к
 * молчащей: её просто нет в знаменателе.
 */
function isMeasured(metric: Metric): metric is MeasuredMetric {
  return metric.score !== null && Number.isFinite(metric.score)
}

/**
 * Метрики обещают вклад в 0..1, но скор сравнивают с порогом, и инвариант
 * «результат лежит в 0..1» должен держаться даже если одна метрика ошиблась в
 * нормировке. Обрезка не чинит метрику, а не даёт её ошибке утечь в порог.
 */
function clamp01(value: number): number {
  if (value < 0) return 0
  if (value > 1) return 1
  return value
}

export function scoreOf(metrics: readonly Metric[]): Scored {
  const total = metrics.length
  const measured = metrics.filter(isMeasured)

  // Ни одного измерения — не «ничего не происходит», а «мы не знаем».
  // Ноль здесь честен ровно потому, что available = 0 говорит об этом прямо.
  if (measured.length === 0) return { score: 0, available: 0, total, top: [] }

  // В top идут только метрики, которые ЧТО-ТО показали. Нулевая метрика —
  // это «события нет», и в подписи пинга она читается как повод, которым не
  // является: «пробоя нет» рядом с «киты набирают» выглядит одинаково веским.
  const top = [...measured]
    .filter((metric) => clamp01(metric.score) > 0)
    .sort((a, b) => clamp01(b.score) - clamp01(a.score))
    .slice(0, MAX_TOP_METRICS)

  // Среднее по ТРЁМ сильнейшим, а не по всем измеренным.
  //
  // Замер на живом рынке 28.08.2026: ZRO упал на 3.9% за час — событие,
  // которое стоит показать. Загорелись две метрики из восьми (импульс 0.25,
  // слабость к рынку 0.41), остальные честно нулевые. Среднее по всем
  // измеренным дало 0.094 — сканер не сработал бы никогда.
  //
  // Причина не в порогах, а в конструкции: сжатие и импульс взаимоисключающие
  // по смыслу (монета не бывает одновременно взведённой и летящей), пробой
  // случается редко, фандинг чаще спокоен. Усреднение по всем гарантирует, что
  // настоящее событие утонет в законно молчащих соседях. Максимум по одной
  // метрике тоже плох — тогда пингует любой одиночный шум. Три сильнейшие
  // требуют, чтобы сошлось несколько признаков, но не все восемь сразу.
  // Ни одна метрика не отличилась — событие отсутствует, скор ноль.
  if (top.length === 0) return { score: 0, available: measured.length, total, top: [] }

  let sum = 0
  for (const metric of top) sum += clamp01(metric.score)

  // Делим на MAX_TOP_METRICS, а не на top.length: иначе монета с одной
  // сработавшей метрикой получала бы её полный балл и обгоняла монету, где
  // сошлись три умеренных.
  //
  // Что это значит на практике, без прикрас: одна метрика на самом максимуме
  // даёт 1/3 = 0.333 и порог 0.30 проходит в одиночку. Это осознанно — ход в
  // четыре ATR за час стоит показать и без подтверждений. Совпадение признаков
  // не требуется, оно лишь делает срабатывание легче.
  return {
    score: sum / MAX_TOP_METRICS,
    available: measured.length,
    total,
    top,
  }
}

/**
 * Насколько скор обязан превышать медиану среза, чтобы считаться событием.
 *
 * Абсолютного порога мало. Замер в облаке 28.08.2026: при коротком архиве часть
 * метрик молчит, а в спокойном рынке «монета сжата» верно почти для всех — и
 * порог прошли 19 кандидатов из 20. Признак, общий для всего рынка, ничего не
 * выделяет: это состояние рынка, а не событие монеты.
 *
 * Поэтому кандидат должен и перебить абсолютную планку, и оторваться от поля.
 * Правило самонастраивающееся: в спокойный день не пройдёт никто, в бурный
 * пройдёт тот, кто действительно выбивается.
 */
export const STANDOUT_MARGIN = 0.15

/** Медиана скоров среза: фон, на котором событие обязано выделяться. */
export function medianScore(scores: readonly number[]): number {
  const sorted = scores.filter((value) => Number.isFinite(value)).sort((a, b) => a - b)
  if (sorted.length === 0) return 0
  const middle = Math.floor(sorted.length / 2)
  return sorted.length % 2 === 0
    ? ((sorted[middle - 1] ?? 0) + (sorted[middle] ?? 0)) / 2
    : sorted[middle] ?? 0
}

/** Выделяется ли кандидат на фоне среза. */
export function standsOut(score: number, median: number): boolean {
  return score >= median + STANDOUT_MARGIN
}
